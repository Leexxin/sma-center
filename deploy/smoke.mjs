// Run only in a disposable QA container, never bind the production authenticator.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHmac } from 'node:crypto';
import { totp } from './totp-auth.mjs';
if (process.env.SMA_CENTER_AUTH_TEST !== '1') throw new Error('Use an isolated QA container with SMA_CENTER_AUTH_TEST=1.');
const origin = 'http://127.0.0.1:3000';
const request = (path, options = {}) => fetch(origin + path, { redirect: 'manual', ...options });
const post = (path, body, cookie = '') => request(path, { method: 'POST', headers: { Origin: origin, Cookie: cookie, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams(body) });
const cookieOf = response => response.headers.getSetCookie().find(c => c.startsWith('sma_center_totp=')).split(';')[0];
if (process.argv.includes('--after-restart')) {
  const cookie = readFileSync('/data/qa-session.txt', 'utf8');
  assert.equal((await request('/api/resources', { headers: { Cookie: cookie } })).status, 200);
  assert.equal((await request('/setup')).headers.get('location'), '/login');
  assert.equal(JSON.parse(readFileSync('/data/totp-auth.json', 'utf8')).ttlSeconds, 300);
  console.log('PASS bound authenticator, session and configured expiry survive restart');
  process.exit(0);
}
assert.equal((await request('/')).headers.get('location'), '/setup');
assert.equal((await request('/security')).headers.get('location'), '/setup');
for (const headers of [{}, { Cookie: 'sma_center_session=old-password-session' }, { 'sma-center-authenticated': 'totp-v1', 'sma-center-owner-id': 'selfhost:admin', 'oai-authenticated-user-id': 'selfhost:admin' }]) assert.equal((await request('/api/resources', { headers })).status, 401);
const publicSetup = await (await request('/setup')).text();
assert.ok(!publicSetup.includes('otpauth://') && !publicSetup.includes('data:image/png'));
assert.equal((await request('/setup/verify')).headers.get('location'), '/setup');
assert.equal((await request('/setup/authorize', { method: 'POST', body: 'setupCode=x' })).status, 403);
assert.equal((await post('/setup/authorize', { setupCode: 'wrong' })).status, 401);
const setupCode = readFileSync('/data/setup-code.txt', 'utf8').trim();
const authorized = await post('/setup/authorize', { setupCode });
assert.equal(authorized.status, 303);
const enrollment = authorized.headers.get('set-cookie').split(';')[0];
const enrollmentPage = await request('/setup/verify', { headers: { Cookie: enrollment } });
assert.equal(enrollmentPage.status, 200);
const html = await enrollmentPage.text();
assert.ok(html.includes('data:image/png;base64,'));
const secret = html.match(/<code class="secret">([A-Z2-7]+)<\/code>/)[1];
assert.equal((await post('/setup/confirm', { code: 'invalid' }, enrollment)).status, 401);
assert.equal((await request('/api/resources')).status, 401);
const bound = await post('/setup/confirm', { code: totp(secret, Math.floor(Date.now() / 30000)) }, enrollment);
assert.equal(bound.status, 303);
let cookie = cookieOf(bound);
assert.ok(bound.headers.get('set-cookie').includes('HttpOnly'));
assert.ok(bound.headers.get('set-cookie').includes('SameSite=Strict'));
const dashboard = await request('/', { headers: { Cookie: cookie } });
assert.equal(dashboard.status, 200);
assert.ok((await dashboard.text()).includes('安全设置'));
assert.equal((await request('/setup/verify', { headers: { Cookie: enrollment } })).headers.get('location'), '/login');
const passwordAttempt = await post('/login', { username: 'admin', password: 'old-password' });
assert.equal(passwordAttempt.status, 401);
assert.equal((await post('/security', { ttlMinutes: '4' }, cookie)).status, 400);
assert.equal((await request('/security', { method: 'POST', headers: { Cookie: cookie, Origin: 'http://evil.invalid' }, body: '' })).status, 403);
const settings = await post('/security', { ttlMinutes: '5' }, cookie);
assert.equal(settings.status, 303); cookie = cookieOf(settings);
assert.equal(JSON.parse(readFileSync('/data/totp-auth.json', 'utf8')).ttlSeconds, 300);
const signingKey = JSON.parse(readFileSync('/data/secrets.json', 'utf8')).session;
const state = JSON.parse(readFileSync('/data/totp-auth.json', 'utf8'));
const expired = Buffer.from(JSON.stringify({ version: 1, issued: Date.now() - 301000, expires: Date.now() + 999999, generation: state.generation, nonce: 'a'.repeat(32) })).toString('base64url');
const forged = expired + '.' + createHmac('sha256', signingKey).update('totp-session-v1.' + expired).digest('base64url');
assert.equal((await request('/api/resources', { headers: { Cookie: 'sma_center_totp=' + forged } })).status, 401);
assert.ok(!readFileSync('/data/totp-auth.json', 'utf8').includes(secret));
assert.equal((await request('/api/backup', { headers: { Cookie: cookie } })).status, 200);
assert.equal((await post('/logout', {}, cookie)).status, 303);
assert.equal((await request('/api/resources', { headers: { Cookie: cookie } })).status, 401);
const nextCounter = Math.floor(Date.now() / 30000) + 1;
const nextCode = totp(secret, nextCounter);
const login = await post('/login', { code: nextCode });
assert.equal(login.status, 303);
cookie = cookieOf(login);
assert.equal((await post('/login', { code: nextCode })).status, 401);
writeFileSync('/data/qa-session.txt', cookie, { mode: 0o600 });
console.log('PASS mandatory binding, QR enrollment, invalid-code rejection, login, password rejection, CSRF, expiry, logout and replay rejection');
